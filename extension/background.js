import { HoardError, save } from "./hoard.js";

chrome.runtime.onInstalled.addListener(() => {
  chrome.contextMenus.removeAll(() => {
    chrome.contextMenus.create({ id: "save-media", title: "Save to Hoard", contexts: ["image", "video", "audio"] });
    chrome.contextMenus.create({ id: "save-link", title: "Save linked file to Hoard", contexts: ["link"] });
    chrome.contextMenus.create({ id: "save-screenshot", title: "Save screenshot of this page to Hoard", contexts: ["page", "selection"] });
  });
});

async function flash(ok, tabId, message) {
  await chrome.action.setBadgeBackgroundColor({ color: ok ? "#46a758" : "#d23d3d" });
  await chrome.action.setBadgeText({ text: ok ? "✓" : "!", tabId });
  await chrome.action.setTitle({ title: message, tabId });
  setTimeout(() => {
    chrome.action.setBadgeText({ text: "", tabId });
    chrome.action.setTitle({ title: "Hoard", tabId });
  }, 4000);
}

async function run(tab, job) {
  try {
    const r = await job();
    await flash(true, tab?.id, r.status === "duplicate" ? "Already in your Hoard library" : "Saved to Hoard");
  } catch (e) {
    await flash(false, tab?.id, e.message || String(e));
    if (e instanceof HoardError && e.kind === "token") chrome.runtime.openOptionsPage();
  }
}

export async function screenshot(tab) {
  const data = await chrome.tabs.captureVisibleTab(tab.windowId, { format: "png" });
  const stamp = new Date().toISOString().slice(0, 19).replace(/[T:]/g, "-");
  return save({ data, fileName: `Screenshot ${stamp}.png`, pageUrl: tab.url, title: tab.title || "Screenshot" });
}

function mediaItem(src, tab, title) {
  if (src.startsWith("data:")) return { data: src, pageUrl: tab.url, title };
  if (src.startsWith("blob:")) throw new HoardError("This file is generated by the page and can't be saved directly. Try a screenshot instead.", "error");
  return { url: src, pageUrl: tab.url, title };
}

chrome.contextMenus.onClicked.addListener((info, tab) => {
  if (info.menuItemId === "save-media" && info.srcUrl) run(tab, () => save(mediaItem(info.srcUrl, tab, tab.title)));
  if (info.menuItemId === "save-link" && info.linkUrl) run(tab, () => save(mediaItem(info.linkUrl, tab, info.selectionText || undefined)));
  if (info.menuItemId === "save-screenshot") run(tab, () => screenshot(tab));
});

chrome.commands.onCommand.addListener(async (cmd, tab) => {
  if (cmd !== "save-screenshot") return;
  tab = tab || (await chrome.tabs.query({ active: true, currentWindow: true }))[0];
  if (tab) run(tab, () => screenshot(tab));
});
